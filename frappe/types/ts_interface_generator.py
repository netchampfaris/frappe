import ast
import inspect
import os
import re
import textwrap
from pathlib import Path
from typing import Union, get_type_hints

import frappe
from frappe.model.base_document import get_controller
from frappe.utils import get_bench_path

HOOK_NAME = "typescript_interface_generator"
DEFAULT_OUTPUT_FILE = "frontend/src/doctypes.ts"
DEFAULT_CLIENT_IMPORT = "@/client"
DEFAULT_EMIT_DEFINITIONS = True


class TSInterfaceGenerator:
	RESERVED_METHOD_NAMES = frozenset(
		{
			"getDoc",
			"getList",
			"newDoc",
			"getCount",
			"bulkDelete",
			"bulkUpdate",
			"onUpdate",
		}
	)

	def __init__(
		self,
		doctypes: str | list[str],
		output_file: str,
		client_import: str = DEFAULT_CLIENT_IMPORT,
		emit_definitions: bool = DEFAULT_EMIT_DEFINITIONS,
	):
		if isinstance(doctypes, str):
			self.doctypes = [d.strip() for d in doctypes.split(",") if d.strip()]
		else:
			self.doctypes = doctypes
		self.output_file = output_file
		self.client_import = client_import
		self.emit_definitions = emit_definitions
		self.generated_interfaces: set[str] = set()
		self.overrides: dict[tuple, str] = {}
		self.existing_hashes: dict[str, str] = {}
		self.existing_blocks: dict[str, list[str]] = {}
		self.reused_doctype_count = 0
		self.regenerated_doctype_count = 0
		self.definition_errors: list[str] = []
		self.parse_existing_file()

	def parse_existing_file(self):
		if not os.path.exists(self.output_file):
			return

		with open(self.output_file, encoding="utf-8") as f:
			content = f.read()

		block_pattern = (
			r"// @doctype: (?P<doctype>[^\n]+)\n// @migration_hash: (?P<hash>\w+)\n"
			r"(?P<block>.*?)\n// @doctype: (?P=doctype) end"
		)
		for match in re.finditer(block_pattern, content, re.DOTALL):
			dt = match.group("doctype")
			self.existing_hashes[dt] = match.group("hash")
			self.existing_blocks[dt] = match.group("block").splitlines()

		lines = content.splitlines()
		context_stack = []
		for line in lines:
			trimmed = line.strip()

			if trimmed.startswith("export interface"):
				context_stack = [trimmed.split()[2]]
			elif trimmed.startswith("export const"):
				context_stack = [trimmed.split()[2]]
			elif trimmed.endswith("{") or trimmed.endswith("({"):
				match = re.search(r"^(?P<key>\w+):", trimmed)
				if match:
					context_stack.append(match.group("key"))
			elif trimmed.startswith("}") or trimmed.startswith("})") or trimmed.startswith("},"):
				if context_stack:
					context_stack.pop()

			if "// @manual" in line:
				match = re.search(r"^\s*(?P<name>\w+\??):", line)
				if match:
					name = match.group("name").replace("?", "")
					full_context = ".".join(context_stack)
					self.overrides[(full_context, name)] = trimmed

	def execute(self):
		lines = [
			"/**",
			" * This file is auto-generated by TSInterfaceGenerator",
			" * Do not edit this file manually.",
			" */",
			"",
		]

		if self.emit_definitions:
			lines.extend(
				[
					f"import {{ defineDoctype }} from '{self.client_import}'",
					"",
				]
			)

		lines.extend(
			[
				"interface DocType {",
				"  name: string",
				"  creation: string",
				"  modified: string",
				"  owner: string",
				"  modified_by: string",
				"  docstatus: 0 | 1 | 2",
				"}",
				"",
				"interface ChildDocType extends DocType {",
				"  parent: string",
				"  parenttype: string",
				"  parentfield: string",
				"  idx: number",
				"}",
				"",
			]
		)

		for doctype in self.doctypes:
			lines.extend(self.generate_for_doctype(doctype))
			lines.append("")

		content = "\n".join(lines)

		output_path = os.path.abspath(self.output_file)
		os.makedirs(os.path.dirname(output_path), exist_ok=True)

		with open(output_path, "w", encoding="utf-8") as f:
			f.write(content)

		display_path = self.get_display_path(output_path)

		mode = "interfaces" if not self.emit_definitions else "interfaces + doctypes"
		return {
			"output": display_path,
			"mode": mode,
			"doctypes": len(self.doctypes),
			"regenerated": self.regenerated_doctype_count,
			"reused": self.reused_doctype_count,
			"definition_errors": len(self.definition_errors),
			"errored_doctypes": self.definition_errors,
		}

	def get_display_path(self, output_path: str) -> str:
		apps_dir = os.path.join(get_bench_path(), "apps")
		try:
			if os.path.commonpath([apps_dir, output_path]) == apps_dir:
				return os.path.relpath(output_path, start=apps_dir)
		except ValueError:
			pass

		try:
			return os.path.relpath(output_path, start=os.getcwd())
		except ValueError:
			return output_path

	def generate_for_doctype(self, doctype: str) -> list[str]:
		meta = frappe.get_meta(doctype)
		current_hash = getattr(meta, "migration_hash", None)
		interface_name = self.get_interface_name(doctype)
		const_name = doctype.replace(" ", "")

		if interface_name in self.generated_interfaces:
			return []

		lines = []
		lines.append(f"// @doctype: {doctype}")
		lines.append(f"// @migration_hash: {current_hash}")

		existing_block = self.existing_blocks.get(doctype, [])
		existing_hash = self.existing_hashes.get(doctype)

		interface_generated = False

		if current_hash and existing_hash == current_hash and existing_block:
			split_idx = -1
			for i, line in enumerate(existing_block):
				if line.strip().startswith("export const"):
					split_idx = i
					break

			if split_idx != -1:
				lines.extend(existing_block[:split_idx])
			else:
				lines.extend(existing_block)
			interface_generated = True
			self.reused_doctype_count += 1

		if not interface_generated:
			self.regenerated_doctype_count += 1
			child_doctypes = []
			for field in meta.fields:
				if field.fieldtype in ["Table", "Table MultiSelect"] and field.options:
					child_doctypes.append(field.options)

			for child_dt in child_doctypes:
				lines.extend(self.generate_interface_only(child_dt, is_child=True))
				lines.append("")

			lines.append(f"export interface {interface_name} extends DocType {{")
			used_fields = set()
			for field in meta.fields:
				if field.fieldtype in ["Section Break", "Column Break", "Tab Break", "HTML", "Button"]:
					continue

				used_fields.add(field.fieldname)

				label = field.label or field.fieldname
				options_suffix = (
					f" ({field.options})" if field.fieldtype in ["Link", "Table", "Table MultiSelect"] else ""
				)
				lines.append(f"  /** {label}: {field.fieldtype}{options_suffix} */")

				override_key = (interface_name, field.fieldname)
				if override_key in self.overrides:
					lines.append("  " + self.overrides[override_key])
					continue

				ts_type = self.get_ts_type(field)
				is_required = field.reqd or (field.default is not None and field.default != "")
				optional = "" if is_required else "?"
				lines.append(f"  {field.fieldname}{optional}: {ts_type}")

			for (ctx, name), content in self.overrides.items():
				if ctx == interface_name and name not in used_fields:
					lines.append("  " + content)

			lines.append("}")
			lines.append("")

		if not self.emit_definitions:
			lines.append(f"// @doctype: {doctype} end")
			self.generated_interfaces.add(interface_name)
			return lines

		existing_methods = self.extract_methods_from_block(existing_block)

		try:
			controller_class = get_controller(doctype)
			doc_methods, controller_methods = self.get_methods(controller_class)

			lines.append(f"export const {const_name} = defineDoctype<{interface_name}>()({{")
			lines.append(f"  doctype: '{doctype}',")

			def append_methods_section(key, methods):
				if not methods and not existing_methods.get(key):
					return

				method_lines = []

				for name, func in methods.items():
					camel_name = self.to_camel_case(name)
					if camel_name in self.RESERVED_METHOD_NAMES:
						continue
					return_ts = self.get_return_ts(func)

					if camel_name in existing_methods.get(key, {}):
						method_lines.extend(
							self.merge_method_lines(existing_methods[key][camel_name], return_ts)
						)
					else:
						method_lines.append(f"    {camel_name}: {{")
						method_lines.append(f"      method: '{name}',")
						method_lines.append(f"      httpMethod: '{self.get_http_method(func)}',")
						args_context = f"{const_name}.{key}.{camel_name}.args"
						method_lines.append(f"      args: {self.get_args_ts(func, args_context)},")
						if return_ts and return_ts != "any":
							method_lines.append(f"      returns: null as unknown as {return_ts},")
						method_lines.append("    },")

				if not method_lines:
					return

				lines.append(f"  {key}: {{")
				lines.extend(method_lines)
				lines.append("  },")

			append_methods_section("controllerMethods", controller_methods)
			append_methods_section("docMethods", doc_methods)

			lines.append("})")
		except Exception as e:
			self.definition_errors.append(f"{doctype}: {e}")

		lines.append(f"// @doctype: {doctype} end")
		self.generated_interfaces.add(interface_name)
		return lines

	def extract_methods_from_block(self, lines: list[str]) -> dict[str, dict[str, list[str]]]:
		extracted = {"docMethods": {}, "controllerMethods": {}}
		if not lines:
			return extracted

		start_idx = -1
		for i, line in enumerate(lines):
			if line.strip().startswith("export const") and "defineDoctype" in line:
				start_idx = i
				break

		if start_idx == -1:
			return extracted

		current_section = None
		current_method = None
		method_lines = []
		brace_balance = 0

		for line in lines[start_idx:]:
			stripped = line.strip()

			if stripped.startswith("controllerMethods: {"):
				current_section = "controllerMethods"
				continue
			if stripped.startswith("docMethods: {"):
				current_section = "docMethods"
				continue

			if current_section:
				if stripped == "},":
					current_section = None
					continue

				if not current_method:
					match = re.search(r"^\s*(?P<name>\w+): \{", line)
					if match:
						current_method = match.group("name")
						method_lines = [line]
						brace_balance = line.count("{") - line.count("}")
				else:
					method_lines.append(line)
					brace_balance += line.count("{") - line.count("}")

				if current_method and brace_balance == 0:
					extracted[current_section][current_method] = method_lines
					current_method = None
					method_lines = []

		return extracted

	def merge_method_lines(self, method_lines: list[str], return_ts: str | None) -> list[str]:
		if not return_ts or return_ts == "any":
			return method_lines

		if any(line.strip().startswith("returns:") for line in method_lines):
			return method_lines

		merged = list(method_lines)
		insert_at = len(merged)
		for i in range(len(merged) - 1, -1, -1):
			if merged[i].strip() in ["}", "},"]:
				insert_at = i
				break

		merged.insert(insert_at, f"      returns: null as unknown as {return_ts},")
		return merged

	def generate_interface_only(self, doctype: str, is_child: bool = False) -> list[str]:
		interface_name = self.get_interface_name(doctype)
		if interface_name in self.generated_interfaces:
			return []

		meta = frappe.get_meta(doctype)
		base = "ChildDocType" if is_child else "DocType"

		lines = []
		lines.append(f"export interface {interface_name} extends {base} {{")
		used_fields = set()
		for field in meta.fields:
			if field.fieldtype in ["Section Break", "Column Break", "Tab Break", "HTML", "Button"]:
				continue

			used_fields.add(field.fieldname)
			label = field.label or field.fieldname
			options_suffix = (
				f" ({field.options})" if field.fieldtype in ["Link", "Table", "Table MultiSelect"] else ""
			)
			lines.append(f"  /** {label}: {field.fieldtype}{options_suffix} */")

			override_key = (interface_name, field.fieldname)
			if override_key in self.overrides:
				lines.append("  " + self.overrides[override_key])
				continue

			ts_type = self.get_ts_type(field)
			is_required = field.reqd or (field.default is not None and field.default != "")
			optional = "" if is_required else "?"
			lines.append(f"  {field.fieldname}{optional}: {ts_type}")

		for (ctx, name), content in self.overrides.items():
			if ctx == interface_name and name not in used_fields:
				lines.append("  " + content)

		lines.append("}")
		self.generated_interfaces.add(interface_name)
		return lines

	def get_interface_name(self, doctype: str) -> str:
		return doctype.replace(" ", "") + "Interface"

	def get_ts_type(self, field):
		if field.fieldtype == "Check":
			return "boolean"
		if field.fieldtype in ["Int", "Float", "Currency", "Percent"]:
			return "number"
		if field.fieldtype in ["Table", "Table MultiSelect"] and field.options:
			return f"{self.get_interface_name(field.options)}[]"
		if field.fieldtype in ["Table", "Table MultiSelect"]:
			return "any[]"
		if field.fieldtype == "Select" and field.options:
			options = [o.strip() for o in field.options.split("\n") if o.strip()]
			if not field.reqd and not field.default and "" not in options:
				options.insert(0, "")
			return " | ".join(f"'{o}'" for o in options)
		return "string"

	def to_camel_case(self, snake_str):
		components = snake_str.split("_")
		return components[0] + "".join(x.title() for x in components[1:])

	def get_methods(self, controller_class):
		doc_methods = {}
		controller_methods = {}

		def is_whitelisted(func):
			if func in frappe.whitelisted:
				return True
			if hasattr(func, "__wrapped__") and func.__wrapped__ in frappe.whitelisted:
				return True
			return False

		for name, method in inspect.getmembers(controller_class, predicate=inspect.isfunction):
			if is_whitelisted(method) and method.__qualname__.startswith(controller_class.__name__ + "."):
				doc_methods[name] = method

		try:
			module = inspect.getmodule(controller_class)
			for name, func in inspect.getmembers(module, predicate=inspect.isfunction):
				if is_whitelisted(func):
					controller_methods[name] = func
		except Exception:
			pass

		return doc_methods, controller_methods

	def get_http_method(self, func):
		methods = frappe.allowed_http_methods_for_whitelisted_func.get(func)
		if not methods and hasattr(func, "__wrapped__"):
			methods = frappe.allowed_http_methods_for_whitelisted_func.get(func.__wrapped__)

		if methods and len(methods) == 1:
			return methods[0]
		return "POST"

	def get_args_ts(self, func, context):
		sig = inspect.signature(func)
		try:
			type_hints = get_type_hints(func)
		except Exception:
			type_hints = {}

		params = []
		for name, param in sig.parameters.items():
			if name == "self":
				continue

			override_key = (context, name)
			if override_key in self.overrides:
				params.append(self.overrides[override_key])
				continue

			ts_type = self.python_to_ts_type(type_hints.get(name, param.annotation))
			if ts_type == "any" and param.default != inspect.Parameter.empty:
				if isinstance(param.default, bool):
					ts_type = "boolean"
				elif isinstance(param.default, (int | float)):
					ts_type = "number"
				elif isinstance(param.default, str):
					ts_type = "string"

			is_optional = param.default != inspect.Parameter.empty
			params.append(f"{name}{'?' if is_optional else ''}: {ts_type}")

		if not params:
			return "() => ({})"

		if len(params) > 3:
			params_str = "\n        ".join(params)
			return f"(params: {{\n        {params_str}\n      }}) => params"
		return f"(params: {{ {', '.join(params)} }}) => params"

	def get_return_ts(self, func):
		try:
			type_hints = get_type_hints(func)
		except Exception:
			type_hints = {}

		return_hint = type_hints.get("return", inspect.signature(func).return_annotation)
		if return_hint != inspect.Signature.empty:
			return self.python_to_ts_type(return_hint)

		return self.infer_return_ts_from_source(func)

	def infer_return_ts_from_source(self, func):
		try:
			source = textwrap.dedent(inspect.getsource(func))
			tree = ast.parse(source)
		except Exception:
			return None

		return_values = [node.value for node in ast.walk(tree) if isinstance(node, ast.Return)]
		if not return_values or all(value is None for value in return_values):
			return "void"

		non_none_returns = [value for value in return_values if value is not None]
		if not non_none_returns:
			return "void"

		if all(isinstance(value, ast.Dict) for value in non_none_returns):
			return "Record<string, any>"
		if all(isinstance(value, ast.List) for value in non_none_returns):
			return "any[]"
		if all(
			isinstance(value, ast.Constant) and isinstance(value.value, bool) for value in non_none_returns
		):
			return "boolean"
		if all(
			isinstance(value, ast.Constant) and isinstance(value.value, (int, float))
			for value in non_none_returns
		):
			return "number"
		if all(
			isinstance(value, ast.Constant) and isinstance(value.value, str) for value in non_none_returns
		):
			return "string"

		return None

	def python_to_ts_type(self, py_type):
		if py_type == inspect.Parameter.empty:
			return "any"
		if py_type is None or py_type is type(None):
			return "void"

		if hasattr(py_type, "__origin__") and py_type.__origin__ is Union:
			args = [a for a in py_type.__args__ if a is not type(None)]
			if len(args) == 1:
				return self.python_to_ts_type(args[0])
			return " | ".join(self.python_to_ts_type(a) for a in args)

		if py_type is str:
			return "string"
		if py_type in [int, float]:
			return "number"
		if py_type is bool:
			return "boolean"
		if py_type is list or (hasattr(py_type, "__origin__") and py_type.__origin__ in [list, list]):
			return "any[]"
		if py_type is dict or (hasattr(py_type, "__origin__") and py_type.__origin__ in [dict, dict]):
			return "Record<string, any>"

		return "any"


def _get_hook_config(app_name: str) -> dict | None:
	config = frappe.get_hooks(HOOK_NAME, app_name=app_name) or {}
	if not config:
		return None

	enabled = _last(config.get("enabled"), True)
	if not enabled:
		return None

	doctypes = list(dict.fromkeys(config.get("doctypes") or []))
	if not doctypes:
		return None

	output_file = _last(config.get("output_file"), DEFAULT_OUTPUT_FILE)
	client_import = _last(config.get("client_import"), DEFAULT_CLIENT_IMPORT)
	emit_definitions = _last(config.get("emit_definitions"), DEFAULT_EMIT_DEFINITIONS)
	app_root = Path(frappe.get_app_path(app_name)).parent
	output_path = Path(output_file)
	if not output_path.is_absolute():
		output_path = app_root / output_path

	return {
		"app_name": app_name,
		"doctypes": doctypes,
		"output_file": str(output_path),
		"client_import": client_import,
		"emit_definitions": emit_definitions,
	}


def _last(values, default=None):
	if values is None:
		return default
	if isinstance(values, list):
		return values[-1] if values else default
	return values


def get_configured_generators(app_name: str | None = None) -> list[dict]:
	apps = [app_name] if app_name else frappe.get_installed_apps()
	configs = []
	for app in apps:
		config = _get_hook_config(app)
		if config:
			configs.append(config)
	return configs


def run_configured_generators(app_name: str | None = None, doctype: str | None = None):
	results = []
	for config in get_configured_generators(app_name=app_name):
		if doctype and doctype not in config["doctypes"]:
			continue

		result = TSInterfaceGenerator(
			config["doctypes"],
			config["output_file"],
			client_import=config["client_import"],
			emit_definitions=config["emit_definitions"],
		).execute()
		result["app"] = config["app_name"]
		results.append(result)

	return {"results": results}


def execute(
	doctype: str | list[str],
	output_file: str,
	client_import: str = DEFAULT_CLIENT_IMPORT,
	emit_definitions: bool = DEFAULT_EMIT_DEFINITIONS,
):
	return TSInterfaceGenerator(
		doctype,
		output_file,
		client_import=client_import,
		emit_definitions=emit_definitions,
	).execute()
